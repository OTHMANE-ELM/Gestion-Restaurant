    private void bnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bnAddActionPerformed
        // TODO add your handling code here:

        Client client = (Client) txtClient.getSelectedItem();
        Plat plat = (Plat) plats.getSelectedItem();
        Date utilDate = txtDate.getDate();
        LocalDate date = utilDate.toInstant()
                .atZone(ZoneId.systemDefault())
                .toLocalDate();
        int qte = (int) quantite.getValue();

        try {
            ms.createCommande(new Commande(date, qte, plat, client));
        } catch (Exception ex) {
            Logger.getLogger(GestionCommande.class.getName()).log(Level.SEVERE, null, ex);
        }

        try {
            load();
        } catch (Exception ex) {
            Logger.getLogger(GestionCommande.class.getName()).log(Level.SEVERE, null, ex);
        }
    }//GEN-LAST:event_bnAddActionPerformed

    private void listeCommandesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_listeCommandesMouseClicked
        // TODO add your handling code here:
        id = Integer.parseInt(model.getValueAt(listeCommandes.getSelectedRow(), 0).toString());

        txtClient.setSelectedItem(model.getValueAt(listeCommandes.getSelectedRow(), 1).toString());

        plats.setSelectedItem(model.getValueAt(listeCommandes.getSelectedRow(), 2));

        LocalDate localDate = (LocalDate) model.getValueAt(listeCommandes.getSelectedRow(), 3);
        txtDate.setDate(java.sql.Date.valueOf(localDate));

        quantite.setValue((int) model.getValueAt(listeCommandes.getSelectedRow(), 4));


    }//GEN-LAST:event_listeCommandesMouseClicked

    private void bnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_bnUpdateActionPerformed
        // TODO add your handling code here:
        Client client = (Client) txtClient.getSelectedItem();
        Plat plat = (Plat) plats.getSelectedItem();
        Date utilDate = txtDate.getDate();
        LocalDate date = utilDate.toInstant()
                .atZone(ZoneId.systemDefault())
                .toLocalDate();
        int qte = (int) quantite.getValue();
        int reponse = JOptionPane.showConfirmDialog(this, "Voulez-vous vraiment modifier cette commande ? ");
        if (reponse == 0) {
            Commande newCommande = new Commande(id, date, qte, plat, client);
            try {
                ms.updateCommande(newCommande);
            } catch (Exception ex) {
                Logger.getLogger(GestionCommande.class.getName()).log(Level.SEVERE, null, ex);
            }
            try {
                load();
            } catch (Exception ex) {
                Logger.getLogger(GestionCommande.class.getName()).log(Level.SEVERE, null, ex);
            }
        }


    }//GEN-LAST:event_bnUpdateActionPerformed


