    void loadPlat() throws Exception {
        for (Plat p : ps.listPlats()) {
            plats.addItem(p);
        }
    }

    void loadClient() throws Exception {
        for (Client c : cs.getClient()) {
            txtClient.addItem(c);
        }

    }

    void load() throws Exception {
        model.setRowCount(0);

        for (Commande m : ms.listCommandes()) {
            model.addRow(new Object[]{
                m.getId_commande(),
                m.getClient(),
                m.getPlat(),
                m.getDate_commande(),
                m.getQuantite_commande()

            });
        }

    }

